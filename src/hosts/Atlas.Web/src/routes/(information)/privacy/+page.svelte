<h1>Privacy policy</h1>
<p>Atlas is a public discussion site. This policy explains what information you share when you use it.</p>

<section aria-labelledby="account">
  <h2 id="account">Your account</h2>
  <p>Atlas uses your email address to manage sign-in, email confirmation, and password resets. Your display name appears alongside contributions you publish.</p>
</section>

<section aria-labelledby="content">
  <h2 id="content">Public contributions and private drafts</h2>
  <p>Published nodes, comments, and public profile details can be viewed by other people. Keep personal information you want to protect out of public contributions. Private drafts are stored in the browser you use to write them.</p>
</section>

<section aria-labelledby="location">
  <h2 id="location">Visitor globe</h2>
  <p>Adding a pin is optional. If you add one, the public globe shows an approximate location without your account name. You can choose a location manually or ask your browser to share one.</p>
</section>

<section aria-labelledby="contact">
  <h2 id="contact">Privacy questions</h2>
  <p>For questions about your information, including requests about access or removal, <a href="mailto:atlas@thepublicthinktank.com?subject=Atlas%20privacy%20question">email Atlas</a>.</p>
</section>
