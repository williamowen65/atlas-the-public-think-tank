<h1>Terms of use</h1>
<p>Atlas is a public space for discussing questions, ideas, and evidence. These terms describe what we expect when you use the site.</p>

<section aria-labelledby="participation">
  <h2 id="participation">Participate respectfully</h2>
  <p>Disagree with ideas without harassing or threatening people. Keep spam, impersonation, and other people’s private information out of your contributions. Share material you created or have permission to share.</p>
</section>

<section aria-labelledby="publishing">
  <h2 id="publishing">Publishing on Atlas</h2>
  <p>Publishing a node or comment makes it available for others to read. Atlas displays your contribution and lets people link to it, discuss it, or build on it with their own nodes.</p>
</section>

<section aria-labelledby="moderation">
  <h2 id="moderation">Moderation</h2>
  <p>Atlas may hide content or restrict access when someone misuses the site. Use <strong>Report node</strong> to flag a contribution for review. For help with an account or a moderation question, visit <a href="/help">Help &amp; Support</a>.</p>
</section>

<section aria-labelledby="availability">
  <h2 id="availability">Changes to Atlas</h2>
  <p>Features may change as Atlas develops, and the site may be temporarily unavailable. See the <a href="/privacy">Privacy policy</a> for information about what you share when you use Atlas.</p>
</section>
